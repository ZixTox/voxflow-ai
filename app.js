const flags = {
    'en': '🇺🇸 EN',
    'es': '🇪🇸 ES',
    'de': '🇩🇪 DE',
    'fr': '🇫🇷 FR'
};

document.addEventListener('DOMContentLoaded', () => {
    // Intersection Observer for scroll animations
    const observerOptions = {
        root: null,
        rootMargin: '0px',
        threshold: 0.1
    };

    const observer = new IntersectionObserver((entries, observer) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('visible');
                observer.unobserve(entry.target);
            }
        });
    }, observerOptions);

    document.querySelectorAll('.fade-in-up').forEach(el => {
        observer.observe(el);
    });

    // Language Switcher Logic
    const langLinks = document.querySelectorAll('.lang-dropdown a');
    const currentLangBtn = document.getElementById('current-lang');

    langLinks.forEach(link => {
        link.addEventListener('click', (e) => {
            e.preventDefault();
            const lang = link.getAttribute('data-lang');
            setLanguage(lang);
        });
    });

    function setLanguage(lang) {
        if(!translations[lang]) return;

        // Update Button Text
        currentLangBtn.innerHTML = `${flags[lang]} <i class="ph ph-caret-down"></i>`;

        // Update all data-i18n elements
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if(translations[lang][key]) {
                el.innerHTML = translations[lang][key];
            }
        });

        // Save preference
        localStorage.setItem('voxflow-lang', lang);
    }

    // Load saved language or default to 'en'
    const savedLang = localStorage.getItem('voxflow-lang') || 'en';
    setLanguage(savedLang);
});
